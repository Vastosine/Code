void init() {}

auto Main([[maybe_unused]] int C = 0) {
    int n;
    cin >> n;
    n *= 4;
    vector<pii> a(n);
    for (auto &[u, v] : a) {
        char c;
        cin >> u >> c;
        if (c == 'R') v = 0;
        if (c == 'Y') v = 1;
        if (c == 'G') v = 2;
        if (c == 'B') v = 3;
    }
    for (int i = 0; i < n; i++) {
        for (int j = i - 1; ~j; j--) {
            if (a[i].first != a[j].first && a[i].second < a[j].second) return false;
        }
    }
    return true;
}

